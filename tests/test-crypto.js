'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'), path=require('node:path'),vm=require('node:vm');
const {webcrypto,createCipheriv}=require('node:crypto');
const ctx={crypto:webcrypto,TextEncoder,TextDecoder,Uint8Array,BigInt,console};
ctx.globalThis=ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/aes.js'),'utf8'),ctx);
const c=ctx.CryptoLab;
function eq(actual,expected,description){assert.equal(c.hex(actual),expected,description);console.log('✓ '+description);}
const key=c.fromHex('000102030405060708090a0b0c0d0e0f');
const p=c.fromHex('00112233445566778899aabbccddeeff');
const ciphertext=c.fromHex('69c4e0d86a7b0430d8cdb78070b4c55a');
eq(c.encryptBlock(key,p),c.hex(ciphertext),'AES-128 FIPS-197 encryption KAT');
eq(c.decryptBlock(key,ciphertext),c.hex(p),'AES-128 FIPS-197 decryption KAT');
const k2=c.fromHex('2b7e151628aed2a6abf7158809cf4f3c');
const iv2=c.fromHex('000102030405060708090a0b0c0d0e0f');
const p2=c.fromHex('6bc1bee22e409f96e93d7e117393172a');
const ct2=c.fromHex('7649abac8119b246cee98e9b12e9197d');
eq(c.cbcEncryptBlock(k2,iv2,p2),c.hex(ct2),'AES-CBC NIST SP 800-38A KAT');
eq(c.cbcDecryptBlock(k2,iv2,ct2),c.hex(p2),'AES-CBC decryption KAT');
const zero=new Uint8Array(16), nonce=new Uint8Array(12);
eq(c.gcmEncrypt(zero,nonce,new Uint8Array()).tag,'58e2fccefa7e3061367f1d57a4e7455a','AES-GCM empty message NIST KAT');
const g=c.gcmEncrypt(zero,nonce,zero);
eq(g.cipher,'0388dace60b6a392f328c2b971b2fe78','AES-GCM ciphertext NIST KAT');
eq(g.tag,'ab6e47d42cec13bdf53a67b21257bddf','AES-GCM 128-bit tag NIST KAT');
const valid=c.gcmDecrypt(zero,nonce,g.cipher,g.tag);
eq(valid.plain,c.hex(zero),'AES-GCM valid tag decrypt');assert.equal(valid.authenticated,true);
const tampered=g.cipher.slice();tampered[0]^=1;
assert.throws(()=>c.gcmDecrypt(zero,nonce,tampered,g.tag),/Authentication failed/);console.log('✓ AES-GCM rejects tampered ciphertext');
const bug=c.gcmDecrypt(zero,nonce,tampered,g.tag,new Uint8Array(0),false);
assert.equal(bug.authenticated,false);assert.equal(bug.plain[0],1);console.log('✓ Vulnerable GCM skip-verification produces altered plaintext');
for(let i=0;i<25;i++){
 const k=c.random(16), n=c.random(12), aad=c.random((i*7)%31), plain=c.random((i*17)%65);
 const enc=c.gcmEncrypt(k,n,plain,aad);
 const ref=createCipheriv('aes-128-gcm',Buffer.from(k),Buffer.from(n));ref.setAAD(Buffer.from(aad));
 const cmp=Buffer.concat([ref.update(Buffer.from(plain)),ref.final()]);
 assert.equal(c.hex(enc.cipher),cmp.toString('hex'));
 assert.equal(c.hex(enc.tag),ref.getAuthTag().toString('hex'));
 eq(c.gcmDecrypt(k,n,enc.cipher,enc.tag,aad).plain,c.hex(plain),'AES-GCM randomized roundtrip '+(i+1));
 const input=c.random(i%18+1);const jsCtr=c.ctr(k,n,input,1);
 const nodeCtr=createCipheriv('aes-128-ctr',Buffer.from(k),Buffer.concat([Buffer.from(n),Buffer.from([0,0,0,1])]));
 const refCtr=Buffer.concat([nodeCtr.update(Buffer.from(input)),nodeCtr.final()]);
 assert.equal(c.hex(jsCtr),refCtr.toString('hex'));
}
const guest=c.utf8('ROLE=GUEST______'),admin=c.utf8('ROLE=ADMIN______');
assert.equal(guest.length,16);assert.equal(admin.length,16);
const k=c.random(16),iv=c.random(16),n=c.random(12);
const cb=c.cbcEncryptBlock(k,iv,guest);const forgedIv=c.xor(iv,c.xor(guest,admin));
eq(c.cbcDecryptBlock(k,forgedIv,cb),c.hex(admin),'CBC IV chosen-plaintext forgery');
const cc=c.ctr(k,n,guest);const forgedCc=c.xor(cc,c.xor(guest,admin));
eq(c.ctr(k,n,forgedCc),c.hex(admin),'CTR malleability forgery without nonce reuse');
const e=c.gcmEncrypt(k,n,guest);const forgedGcm=c.xor(e.cipher,c.xor(guest,admin));
assert.throws(()=>c.gcmDecrypt(k,n,forgedGcm,e.tag),/Authentication failed/);
eq(c.gcmDecrypt(k,n,forgedGcm,e.tag,undefined,false).plain,c.hex(admin),'GCM broken-tag-verification chosen-plaintext forgery');
const known=c.utf8('TOKEN=KNOWNVALUE');const target=c.utf8('TOKEN=ABCDEFGHIJ');assert.equal(known.length,16);assert.equal(target.length,16);
const ctKnown=c.ctr(k,n,known),ctTarget=c.ctr(k,n,target);
eq(c.xor(c.xor(known,ctKnown),ctTarget),c.hex(target),'CTR repeated keystream known-plaintext recovery');
const gm1=c.gcmEncrypt(k,n,known),gm2=c.gcmEncrypt(k,n,target);
eq(c.xor(c.xor(known,gm1.cipher),gm2.cipher),c.hex(target),'GCM repeated nonce known-plaintext recovery');
console.log('\nAll crypto and exploit tests passed.');
